# -*- coding: utf-8 -*-
"""
Regenerates src/lib/data/media.ts from what is actually on disk.

    python scripts/build-media-manifest.py

Two indexes, both derived by walking public/ rather than hand-maintained:

    categoryPhotos   public/categories/<family>.*   one photo per part family
    brandLogos       public/brands/<slug>.*         manufacturer wordmarks

Run this after adding, removing or replacing any of those files. Nothing in
src/ names an individual image, so dropping OFG's own photography into the
same directories and re-running this is the whole migration.

Anything missing is simply absent from the manifest, and the UI falls back:
a family with no photo keeps the generated SVG render from
build-part-images.py, and a brand with no logo keeps its wordmark set as text.
A partial set is the normal case here, not an error.

WHY ONE PHOTO PER FAMILY AND NOT PER PRODUCT

Per-product photography would be better and is the intended end state — but it
has to come from OFG. See the note in fetch-reference-media.py: the only
product shots available during design carried another shop's watermark across
the part itself, so the catalogue grid stays on the generated renders, which at
least differ from one product to the next. A single real photograph is used
where a single image genuinely represents the whole group: the category card,
the mega-menu panel, the listing header.

To move to per-product photography later, add a `public/products/<sku>.*`
directory, index it here, and have `productImages()` in ./products.ts prefer it.

No dependencies beyond the standard library.
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLIC = os.path.join(ROOT, "public")
OUT = os.path.join(ROOT, "src", "lib", "data", "media.ts")

EXTENSIONS = (".webp", ".jpg", ".jpeg", ".png", ".avif")

HEADER = '''/**
 * Index of the imagery present under public/.
 *
 * GENERATED by scripts/build-media-manifest.py — do not edit by hand. Add or
 * replace files under public/categories/ or public/brands/ and re-run it.
 */

/**
 * One photograph per part family — the families in `partFamily()` in
 * ./products.ts. A family absent here falls back to its generated SVG render.
 */
export const categoryPhotos: Record<string, string> = {
'''

MIDDLE = '''
/**
 * Manufacturer wordmarks, keyed by brand slug (see ./brands.ts).
 * A brand absent here renders as text instead.
 */
export const brandLogos: Record<string, string> = {
'''

FOOTER = '''
/** Photograph for one part family, or undefined when none is supplied. */
export function photoForFamily(family: string): string | undefined {
  return categoryPhotos[family];
}

/** Wordmark for one brand, or undefined when none is supplied. */
export function logoFor(brandSlug: string): string | undefined {
  return brandLogos[brandSlug];
}
'''


def scan(directory, prefix, skip=()):
    """Map bare filename -> public path, for every image in `directory`."""
    found = {}
    if not os.path.isdir(directory):
        return found
    for name in sorted(os.listdir(directory)):
        stem, extension = os.path.splitext(name)
        if extension.lower() not in EXTENSIONS:
            continue
        if any(stem.startswith(s) for s in skip):
            continue
        found[stem] = f"{prefix}/{name}"
    return found


def emit(entries, out):
    for key, path in entries.items():
        name = key if key.replace("_", "").isalnum() else f'"{key}"'
        out.append(f'  {name}: "{path}",\n')


def main():
    families = scan(os.path.join(PUBLIC, "categories"), "/categories")
    # public/brands/ also holds OFG's own logo variants, which are not
    # manufacturer wordmarks and must not land in the brand index.
    logos = scan(os.path.join(PUBLIC, "brands"), "/brands", skip=("ofg-",))

    out = [HEADER]
    emit(families, out)
    out.append("};\n")
    out.append(MIDDLE)
    emit(logos, out)
    out.append("};\n")
    out.append(FOOTER)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("".join(out))

    print(f"wrote {OUT}")
    print(f"  category photos: {len(families)} ({', '.join(families) or 'none'})")
    print(f"  brand logos:     {len(logos)}")


if __name__ == "__main__":
    main()
